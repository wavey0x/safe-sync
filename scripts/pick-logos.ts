async function get(url: string) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url}: ${res.status}`)
  return res
}
// Shown as <img>, so nothing in an SVG can run; this only drops what a 14px icon doesn't need.
const svgUri = (svg: string) => `data:image/svg+xml,${svg.replace(/<svg[^>]*>/, tag => tag.replace(/\s+(class|width|height)="[^"]*"/g, '')).replace(/>\s+</g, '><').replace(/\s+/g, ' ').trim()
  .replace(/"/g, "'").replace(/[%#<>]/g, c => encodeURIComponent(c))}`
async function pictureUri({ url, disc }: { url: string; disc?: string }) {
  const dir = `${import.meta.dir}/../node_modules/.cache/logos`, src = `${dir}/src`, out = `${dir}/out.png`
  await Bun.write(src, await (await get(url)).arrayBuffer())
  const sips = Bun.spawnSync(['sips', '-s', 'format', 'png', '-z', '36', '36', src, '--out', out])
  if (sips.exitCode) throw new Error(`sips: ${sips.stderr}`)
  const png = `data:image/png;base64,${Buffer.from(await Bun.file(out).arrayBuffer()).toString('base64')}`
  return disc ? svgUri(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><rect width="24" height="24" fill="${disc}"/><image href="${png}" x="3" y="3" width="18" height="18"/></svg>`) : png
}

const missing = CHAINS.filter(c => !ICON[c.id] && !PICTURE[c.id])
if (missing.length) throw new Error(`No logo source for ${missing.map(c => `${c.name} (${c.id})`).join(', ')}: add one to ICON or PICTURE`)
const names = [...new Set(CHAINS.flatMap(c => (ICON[c.id] ? [ICON[c.id]] : [])))].sort()
const icons = Object.fromEntries(await Promise.all(names.map(async n => [n, svgUri(await (await get(`${WEB3ICONS}/${n}.svg`)).text())])))
const pictures: Record<number, string> = {}
for (const c of CHAINS) if (!ICON[c.id]) pictures[c.id] = await pictureUri(PICTURE[c.id])

const licence = (await (await get(`${REPO}/LICENCE`)).text()).trim()
const q = JSON.stringify
await Bun.write(`${import.meta.dir}/../src/logos.ts`, `// Generated by scripts/pick-logos.ts: web3icons (MIT) network icons, and Safe's chain logos for the rest.
/*! Chain logos from web3icons, github.com/0xa3k5/web3icons
${licence.replace(/\*\//g, '* /')} */
const icon: Record<string, string> = {
${names.map(n => `  ${q(n)}: ${q(icons[n])},`).join('\n')}
}

/** Each chain's logo as a data URI, shown round. */
export const LOGO: Record<number, string> = {
${CHAINS.map(c => `  ${c.id}: ${ICON[c.id] ? `icon[${q(ICON[c.id])}]` : q(pictures[c.id])}, // ${c.name}`).join('\n')}
}
`)
console.log(`src/logos.ts: ${CHAINS.length} chains, ${names.length} web3icons, ${Object.keys(pictures).length} pictures`)
